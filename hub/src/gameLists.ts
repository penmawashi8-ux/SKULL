// これまでゲームの絞り込みはトップページのジャンルフィルタ（Reactのstate）
// だけで、URLが増えなかった。そのため各ページから辿れる先が少なく、
// サイトとしての構造が外から見えない状態だった。
// 軸ごとに実URLのページを用意して、全ページ共通のフッターから張る。

import { games, type Game } from './games'

/** '1〜6人（CPU可）' → 6 / '1人〜' → 99 / '1人' → 1 のように上限人数を取り出す。 */
export function maxPlayers(game: Game): number {
  const range = game.players.match(/〜\s*(\d+)\s*人/)
  if (range) return Number(range[1])
  if (/人\s*〜/.test(game.players)) return 99
  const single = game.players.match(/(\d+)\s*人/)
  return single ? Number(single[1]) : 1
}

